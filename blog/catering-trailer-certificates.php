<p>Getting this wrong does not just risk a fine. It can invalidate your insurance, which
means one incident could take the business with it. The good news is that the list is
short and most of it is straightforward once somebody lays it out in order.</p>

<p>Here is what you need, roughly in the order you need it.</p>

<h2>1. Register with your local authority</h2>

<p>Before anything else. You register your food business with the council where you are
based, and the rule is at least <strong>28 days before you start trading</strong>.
Registration is free and it cannot be refused.</p>

<p>Do this early, because you generally cannot get a street trading licence without being
registered first, and 28 days arrives faster than people expect when they are waiting on a
build.</p>

<h2>2. Food hygiene training</h2>

<p>Whoever handles food needs training proportionate to what they do. In practice that
means a Level 2 Food Safety and Hygiene qualification for the people cooking and serving.
It is a short course, it is inexpensive, and an environmental health officer will ask
about it on their first visit.</p>

<p>You will also need a documented food safety management system. For most mobile caterers
that means working through the Food Standards Agency's Safer Food, Better Business pack
and keeping the diary up to date. Keeping it up to date is the part people drop, and it is
the part that gets checked.</p>

<h2>3. Gas safety certificate</h2>

<p>If your trailer burns gas, this one is not negotiable. Gas work on a mobile catering
unit must be carried out by an engineer who is Gas Safe registered <em>with the correct
mobile catering endorsement</em>. A domestic gas engineer is not automatically qualified
for it, and this catches people out.</p>

<p>You need the installation certified, and then re-tested annually. Most event organisers
and most councils will ask to see a current certificate before they let you on a pitch, so
in practice it is also a commercial necessity, not just a legal one.</p>

<div class="callout">
  <p><strong>Buying second hand?</strong> Ask for the gas certificate and look at the
  date before you pay, not after. A trailer sold without one frequently needs remedial
  work before an engineer will issue one, and that cost lands on you.</p>
</div>

<h2>4. Electrical certificate</h2>

<p>Your electrical installation should be inspected and tested, and your appliances PAT
tested. Any competent event organiser will ask for the paperwork, and your insurer will
expect it to exist if you ever claim for a fire.</p>

<p>If you are running from a generator or from an event hook-up, make sure the trailer has
proper RCD protection. This is the single most common thing we find missing when an older
trailer comes in for a refit.</p>

<h2>5. Insurance</h2>

<p>Not a certificate exactly, but it belongs on the list. You want public liability as a
minimum, almost always five million pounds because that is what event organisers ask for,
plus cover for the trailer itself against damage, fire and theft.</p>

<p>Read what your policy says about the trailer while it is detached and parked. Trailer
theft is one of the most common and most expensive losses in this trade, and cover varies
a lot between insurers.</p>

<h2>6. Street trading licence, if you need one</h2>

<p>If you are trading on or beside a public highway you will usually need a street trading
consent or licence from the council for that area. Private land, festivals and private
events generally work differently and the organiser handles the permissions.</p>

<p>This one is genuinely local. Two neighbouring authorities can take quite different
views, so ring the council covering your intended pitch and ask directly rather than
assuming.</p>

<h2>The order that saves you time</h2>

<ol>
  <li>Ring the council covering your pitch and ask what they require. Do this first, before you spend money.</li>
  <li>Register the food business, at least 28 days out.</li>
  <li>Book the Level 2 hygiene course while the trailer is being built.</li>
  <li>Get gas and electrical certification with the trailer, not afterwards.</li>
  <li>Arrange insurance before you collect it.</li>
  <li>Apply for a street trading licence if your pitch needs one.</li>
</ol>

<p>When we build a trailer, the gas certificate and the electrical certificate are handed
over on collection day. That is deliberate. Chasing paperwork with a finished trailer and
an empty pitch is a bad few weeks, and it is entirely avoidable.</p>

<p>Rules change and councils differ, so treat this as a starting point rather than legal
advice, and confirm the detail with your own local authority.</p>

