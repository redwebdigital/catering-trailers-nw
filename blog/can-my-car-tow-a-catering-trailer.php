<p>This is the mistake we see more than any other, and it is the worst one to make because
it is not fixable afterwards. People commission a trailer, wait eight weeks, then discover
the car on the drive cannot legally pull it.</p>

<p>Twenty minutes now saves that. There are only three numbers involved.</p>

<h2>The three numbers</h2>

<h3>1. Your car's maximum towing mass</h3>

<p>Every vehicle has a maximum braked towing mass set by the manufacturer. It is on the
V5C registration document and usually on the VIN plate under the bonnet or in the door
shut. This is a hard limit. It is not advisory and it is not negotiable.</p>

<p>A small hatchback might be 750kg to 1,000kg. A mid-size estate or crossover is often
1,400kg to 1,800kg. A proper pickup or large 4x4 is frequently 2,500kg to 3,500kg.</p>

<h3>2. The trailer's gross weight</h3>

<p>Not the empty weight. The <strong>gross</strong> weight, which is the trailer plus
everything in it: appliances, gas bottles, water, stock and the generator. This is the
number on the trailer's plate, and it is what counts legally.</p>

<p>A loaded catering trailer is heavier than people assume. Water alone is a kilo a litre,
and a full 50 litre tank is 50kg before you have put a single burger in the fridge.</p>

<h3>3. Your licence category</h3>

<p>This depends on when you passed your driving test.</p>

<ul>
  <li><strong>Passed before 1 January 1997:</strong> you generally hold grandfather rights and can tow much heavier combinations. Check your licence for category BE and for C1E.</li>
  <li><strong>Passed on or after 1 January 1997:</strong> the rules were relaxed in recent years and category B drivers in Great Britain can now tow heavier trailers than they once could. The vehicle and trailer weight limits still apply though, and the rules differ in Northern Ireland.</li>
</ul>

<p>Licence entitlement rules have moved about in the last few years, so check your own
record on the GOV.UK "view your driving licence" service rather than relying on what
somebody told you at a show.</p>

<div class="callout">
  <p><strong>The 85 percent guideline.</strong> Separately from the law, the widely used
  guidance is that a trailer's loaded weight should be no more than about 85 percent of
  the towing vehicle's kerbweight for comfortable, stable towing. It is not a legal limit,
  but a trailer at 100 percent of the car's weight is unpleasant and unstable at speed,
  particularly in crosswinds on a motorway.</p>
</div>

<h2>Worked example</h2>

<p>Say you have a 3.5m twin axle trailer with a gross weight of 2,000kg, and a family
estate rated to tow 1,600kg braked.</p>

<p>That combination is illegal, regardless of your licence. The car's limit is the car's
limit. Your options are a lighter trailer, a heavier tow vehicle, or a fundamental rethink,
and all three are far cheaper to discover now than in eight weeks' time.</p>

<h2>The things people forget to weigh</h2>

<ul>
  <li><strong>The generator.</strong> A 6kVA unit is commonly 80kg to 100kg.</li>
  <li><strong>Gas bottles.</strong> A full 47kg propane bottle weighs about 80kg with the cylinder. Two of them is a passenger.</li>
  <li><strong>Water.</strong> One kilo per litre, and it moves about while you drive.</li>
  <li><strong>Stock.</strong> A full fridge and freezer is easily 100kg.</li>
  <li><strong>Nose weight.</strong> A separate limit again, usually 50kg to 100kg, and exceeding it makes the car handle badly even when the total weight is fine.</li>
</ul>

<h2>What to do before you order anything</h2>

<ol>
  <li>Find your V5C and note the maximum braked towing mass.</li>
  <li>Check your licence entitlement on GOV.UK.</li>
  <li>Tell your trailer builder both numbers before the drawing is finalised.</li>
</ol>

