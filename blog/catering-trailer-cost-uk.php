<h2>The four things that actually move the price</h2>

<h3>1. Appliances, by a mile</h3>

<p>The trailer is the cheap part. A six burner range, a twin fryer, a griddle, a bain
marie and an extraction canopy sized to cope with all of it can be half the total. This is
also where you have the most control: bring appliances you already own and the number
drops immediately.</p>

<h3>2. Length, and therefore the axle</h3>

<p>Going from 3.0m to 3.5m is not just half a metre of panel. Past a certain weight you
need a twin axle, which brings a second set of hubs, brakes and suspension, and it changes
what can tow it. That is a step in the price, not a slope.</p>

<h3>3. Water and hygiene provision</h3>

<p>Hot and cold water, a twin sink, a separate wash hand basin and a water heater are not
optional if you want to pass an inspection, and they are a meaningful chunk of the build.
Anyone quoting you significantly under the market has usually left these out. Ask.</p>

<h3>4. Whether certification is included</h3>

<p>A quote with the Gas Safe certificate and the electrical certificate in it is not the
same quote as one without, even when the number looks similar. Compare like for like, and
be suspicious of the cheapest one until you have read what it includes.</p>

<h2>The cost people forget</h2>

<p>Traders budget for the trailer and forget the rest of the start-up. Before you take a
penny you will also need public liability insurance, trailer insurance, a food hygiene
qualification, registration with your local authority, a street trading licence if you are
pitching on the highway, and in most cases a generator.</p>

<p>None of those are enormous individually. Together they are commonly a few thousand
pounds, and running out of money at that stage, with a finished trailer sitting on the
drive, is a genuinely miserable place to be. Build them into the plan from the start.</p>

<h2>Is buying second hand a mistake?</h2>

<p>No, but going in blind is. A used trailer with a sound galvanised chassis, current
certificates and an honest seller is a good buy. A used trailer with surface rust on the
rails, no gas certificate and a vague history is a project, and it should be priced like
one.</p>

<p>Before you hand over money on a used unit, do three things. Get underneath it and look
at the chassis rails. Ask for the gas certificate and check the date. And check the plated
weight against what your vehicle can legally tow, because that one is not fixable
afterwards.</p>

